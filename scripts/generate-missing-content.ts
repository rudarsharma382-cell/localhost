import fs from 'node:fs';
import path from 'node:path';
import { profile } from '../src/content/profile';
import { projects } from '../src/content/projects';
import { validateAllContent, isTodo } from '../src/content';

interface MissingItem {
  category: string;
  item: string;
  file: string;
  details: string;
}

function run(): void {
  const missing: MissingItem[] = [];

  // 1. Validate content schemas
  try {
    validateAllContent();
  } catch (err) {
    console.error('Content validation failed:', err);
    process.exit(1);
  }

  // 2. Check Profile
  if (isTodo(profile.intro)) {
    missing.push({
      category: 'Profile',
      item: 'Personal Bio / Intro',
      file: 'src/content/profile.ts',
      details: profile.intro,
    });
  }
  if (!fs.existsSync(path.resolve(process.cwd(), 'public/avatar.png'))) {
    missing.push({
      category: 'Assets',
      item: 'Avatar Image (`public/avatar.png`)',
      file: 'public/avatar.png',
      details: 'Required for lock screen owner card and About Me profile header.',
    });
  }

  // 3. Check About.md
  const aboutPath = path.resolve(process.cwd(), 'src/content/about.md');
  if (fs.existsSync(aboutPath)) {
    const aboutContent = fs.readFileSync(aboutPath, 'utf-8').trim();
    if (aboutContent.length === 0 || aboutContent.includes('TODO')) {
      missing.push({
        category: 'Editorial Copy',
        item: 'About Me Copy (`src/content/about.md`)',
        file: 'src/content/about.md',
        details: 'PRD Sec 7.3: Must be written by Rudar in personal voice. No fabricated bio.',
      });
    }
  }

  // 4. Check Projects
  for (const proj of projects) {
    if (proj.problem && isTodo(proj.problem)) {
      missing.push({
        category: 'Project Write-ups',
        item: `${proj.name}: Problem Statement`,
        file: 'src/content/projects.ts',
        details: proj.problem,
      });
    }
    if (proj.why && isTodo(proj.why)) {
      missing.push({
        category: 'Project Write-ups',
        item: `${proj.name}: Project Motivation / Why`,
        file: 'src/content/projects.ts',
        details: proj.why,
      });
    }
    if (proj.contribution && isTodo(proj.contribution)) {
      missing.push({
        category: 'Project Write-ups',
        item: `${proj.name}: Individual Contribution`,
        file: 'src/content/projects.ts',
        details: proj.contribution,
      });
    }
    if (!proj.liveUrl) {
      missing.push({
        category: 'Project URLs',
        item: `${proj.name}: Live URL`,
        file: 'src/content/projects.ts',
        details: 'Needed for Browser app live iframe or external view.',
      });
    }
    if (!proj.repoUrl) {
      missing.push({
        category: 'Project URLs',
        item: `${proj.name}: Public Repository URL`,
        file: 'src/content/projects.ts',
        details: 'Needed for Development Studio repository link (if public).',
      });
    }
  }

  // 5. Check Assets (Resume, Wallpapers)
  if (!fs.existsSync(path.resolve(process.cwd(), 'public/resume.pdf'))) {
    missing.push({
      category: 'Assets',
      item: 'Resume PDF (`public/resume.pdf`)',
      file: 'public/resume.pdf',
      details: 'Required for Resume viewer app. Empty state rendered until provided.',
    });
  }

  // 6. PRD Section 22 human tasks (Environment & Headers)
  const prdHumanTasks: MissingItem[] = [
    {
      category: 'Hosting & Security',
      item: 'Frame Ancestors CSP Header on Vercel Projects',
      file: 'Vercel Deployment Settings',
      details: "Set `Content-Security-Policy: frame-ancestors 'self' https://<rudar-os-domain>` and remove `X-Frame-Options: DENY` on live project deployments so the Browser app can embed them.",
    },
    {
      category: 'Backend Credentials',
      item: 'Notes Database (Supabase / Neon connection string)',
      file: '.env.local',
      details: 'Required when building Phase 6 Notes app. Route handlers require DB credentials.',
    },
  ];

  // Generate Markdown
  let md = '# MISSING CONTENT & HUMAN TASKS REPORT\n\n';
  md += '> Automatically generated by `scripts/generate-missing-content.ts`.\n';
  md += '> This report tracks all pending content, assets, and human configuration required from Rudar.\n';
  md += '> **Strict Policy**: No content is ever fabricated. Missing items degrade gracefully.\n\n';
  md += `**Last Updated:** ${new Date().toISOString()}\n\n`;
  md += '## Summary\n\n';
  md += `- **Pending Content Items:** ${missing.length}\n`;
  md += `- **Infrastructure / Human Tasks:** ${prdHumanTasks.length}\n\n`;

  // Group by category
  const categories = Array.from(new Set([...missing, ...prdHumanTasks].map((i) => i.category)));

  for (const cat of categories) {
    md += `### ${cat}\n\n`;
    const items = [...missing, ...prdHumanTasks].filter((i) => i.category === cat);
    for (const item of items) {
      md += `- [ ] **${item.item}**\n`;
      md += `  - *File/Target:* \`${item.file}\`\n`;
      md += `  - *Details:* ${item.details}\n\n`;
    }
  }

  const outputPath = path.resolve(process.cwd(), 'MISSING_CONTENT.md');
  fs.writeFileSync(outputPath, md, 'utf-8');
  console.log(`Updated MISSING_CONTENT.md successfully with ${missing.length + prdHumanTasks.length} pending items.`);
}

run();
